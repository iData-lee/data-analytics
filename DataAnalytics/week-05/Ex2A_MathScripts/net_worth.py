# To calculate net worth one must subtract total debts from total assets. 
# Assets includes cash, investments and real estate. 
# Debts can include loans, credit card balances, personal borrowing from items, and money owed by local government or businesses.

total_asset = 250000 # fictional scenario
total_debt = 15000 
net_worth = total_asset - total_debt

print(f'Your total assets are {total_asset}.')
print(f'Your total debts are {total_debt}.')
print(f'Your net worth is {net_worth}.')